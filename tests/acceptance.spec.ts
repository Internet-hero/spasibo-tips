test('TV-режим автоматически листает стену и закрывается по Escape', async ({ page }) => {
  const errors = monitor(page)
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.goto(route('/wall/venue-coffee?tv=1'))
  const feed = page.locator('.tv-scroll')
  await expect(feed).toBeVisible()
  await page.waitForTimeout(3900)
  expect(await feed.evaluate((element) => element.scrollTop)).toBeGreaterThan(0)
  await page.getByRole('button', { name: 'Приостановить автоскролл' }).click()
  await page.keyboard.press('Escape')
  await expect(page).toHaveURL(/\/#\/wall\/venue-coffee$/)
  expect(errors).toEqual([])
})

