import { expect, test } from '@playwright/test'
import type { Page } from '@playwright/test'
import { readFile } from 'node:fs/promises'
import { route } from './routes'

function monitor(page: Page) {
  const errors: string[] = []
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => { if (message.type() === 'error') errors.push(message.text()) })
  page.on('response', (response) => { if (response.status() >= 400) errors.push(`${response.status()} ${response.url()}`) })
  return errors
}

test('полный путь: QR стола → цель → оплата → стена → сотрудник → CSV', async ({ page }) => {
  const errors = monitor(page)
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto(route('/p/table7/select'))
  await expect(page.getByText('3 из 5 за этим столом уже сказали спасибо')).toBeVisible()
  await page.getByPlaceholder('Имя или должность').fill('Анна')
  await page.locator('a[href^="#/p/table7?staff="]').filter({ hasText: 'Анна' }).click()
  await expect(page.getByRole('heading', { name: 'Анна', exact: true })).toBeVisible()
  await page.getByRole('button', { name: /Добить до цели/ }).click()
  await expect(page.getByLabel('Или своя сумма')).toHaveValue('150')
  await page.getByLabel('Представьтесь').fill('Дмитрий')
  await page.getByLabel(/Тёплые слова/).fill('Спасибо за утро и за раф — приёмочный тест')
  await page.getByRole('button', { name: /Сказать спасибо · 150/ }).click()
  await expect(page.getByRole('dialog')).toBeVisible()
  await page.getByRole('button', { name: /Оплатить 150/ }).click()
  await page.waitForURL(/\/pay\/.*\/status/)
  await expect(page.getByRole('heading', { name: 'Спасибо уже в пути' })).toBeVisible()
  await expect(page.getByText(/Вы 4-й из 5/)).toBeVisible()
  await expect(page.getByText(/Вы помогли закрыть цель/)).toBeVisible()
  await page.getByRole('link', { name: 'Посмотреть на стене' }).click()
  await expect(page.getByText(/приёмочный тест/)).toBeVisible()
  await page.goto(route('/'))
  await page.getByRole('button', { name: /Сотрудник Смена, цель/ }).click()
  await expect(page.getByRole('heading', { name: 'Добрый день, Анна' })).toBeVisible()
  await expect(page.getByText('Добил цель').first()).toBeVisible()
  await expect(page.getByText(/приёмочный тест/).first()).toBeVisible()
  await page.goto(route('/'))
  await page.getByRole('button', { name: /Управляющий Команда, аналитика/ }).click()
  await expect(page.getByRole('heading', { name: 'Пульс заведения' })).toBeVisible()
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: 'CSV' }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/\.csv$/)
  const path = await download.path()
  const csv = await readFile(path!, 'utf8')
  expect(csv).toContain('приёмочный тест')
  expect(csv).toContain('150')
  expect(errors).toEqual([])
})

